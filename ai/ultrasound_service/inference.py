"""Runs the two ultrasound models on uploaded frames.

Both models are research baselines trained on public datasets (SegThy for the neck, CAMUS for the
heart). They report geometry only and are not validated on astronauts or for clinical use.

The measurement code is the repository's own (jugular_geometry.py, camus_geometry.py); this module
only prepares an uploaded picture the way each training pipeline prepared its frames.
"""
import base64
import io
import json
import sys
import threading
from pathlib import Path

import numpy as np
import torch
from PIL import Image, ImageDraw, PngImagePlugin

AI = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(AI / "jugular_ultrasound"))
sys.path.insert(0, str(AI / "heart_ultrasound"))

import camus_pipeline  # noqa: E402
import jugular_pipeline  # noqa: E402
from camus_data import SIZE  # noqa: E402
from camus_geometry import FEATURES, patient_features  # noqa: E402
from jugular_data import SPACING  # noqa: E402
from jugular_geometry import report_line  # noqa: E402

JUGULAR_FITS = AI / "jugular_ultrasound" / "results" / "fits"
HEART_MODEL = AI / "heart_ultrasound" / "final_model"
HEART_FRAMES = ("2CH_ED", "2CH_ES", "4CH_ED", "4CH_ES")
MAX_SIDE = 1024
F = torch.nn.functional

# Overlay colours (red, green, blue) per mask label.
JUGULAR_COLOURS = {1: (240, 196, 60), 2: (226, 72, 72), 3: (64, 132, 240)}   # thyroid, carotid artery, jugular vein
HEART_COLOURS = {1: (226, 72, 72), 2: (240, 196, 60), 3: (64, 132, 240)}     # left ventricle cavity, heart muscle, left atrium

_lock = threading.Lock()  # PyTorch runs one request at a time; the models are small
_heart = None


class BadInput(ValueError):
    """The request cannot be analysed; the message is safe to show to the person."""


def read_image(data):
    """Base64 PNG or JPEG -> 2D float32 greyscale array, at most MAX_SIDE pixels on its longer side."""
    try:
        img = Image.open(io.BytesIO(base64.b64decode(data, validate=True)))
        if img.format not in ("PNG", "JPEG"):
            raise BadInput("Use a PNG or JPEG image.")
        img = img.convert("L")
    except BadInput:
        raise
    except Exception:
        raise BadInput("That file could not be read as an image.") from None
    if min(img.size) < 32:
        raise BadInput("The image is too small to analyse.")
    if max(img.size) > MAX_SIDE:
        k = MAX_SIDE / max(img.size)
        img = img.resize((max(int(img.width * k), 32), max(int(img.height * k), 32)), Image.Resampling.BILINEAR)
    return np.asarray(img, dtype="float32")


def spacing_mm(image, depth_cm):
    """Millimetres per pixel, taking the image height as the depth shown on the scanner."""
    if not isinstance(depth_cm, (int, float)) or isinstance(depth_cm, bool) or not 1 <= depth_cm <= 30:
        raise BadInput("Image depth must be between 1 and 30 cm.")
    return float(depth_cm) * 10.0 / image.shape[0]


def overlay_png(mask, shape, colours):
    """A same-size prediction overlay with a baked-in SI label and provenance metadata."""
    labels = np.asarray(Image.fromarray(mask.astype("uint8")).resize((shape[1], shape[0]), Image.Resampling.NEAREST))
    rgba = np.zeros((*shape, 4), dtype="uint8")
    for label, colour in colours.items():
        rgba[labels == label] = (*colour, 120)
    overlay = Image.fromarray(rgba, "RGBA")
    # Label only the derived overlay, after prediction; never alter measurement inputs or masks.
    label = "SI-generated overlay" if shape[1] >= 128 else "SI"
    draw = ImageDraw.Draw(overlay)
    box = draw.textbbox((0, 0), label)
    width, height = box[2] - box[0] + 8, box[3] - box[1] + 6
    top = max(0, shape[0] - height)
    draw.rectangle((0, top, width, shape[0]), fill=(10, 20, 30, 255))
    draw.text((4 - box[0], top + 3 - box[1]), label, fill=(255, 255, 255, 255))
    metadata = PngImagePlugin.PngInfo()
    metadata.add_text("Description", "SI-generated ultrasound segmentation overlay. Underlying scan is a source image, not SI-generated by this service.")
    metadata.add_text("Software", "Guardian ultrasound machine-learning service")
    out = io.BytesIO()
    overlay.save(out, format="PNG", optimize=True, pnginfo=metadata)
    return base64.b64encode(out.getvalue()).decode("ascii")


def clean(value):
    """Plain JSON: numpy numbers become Python numbers and not-a-number becomes null."""
    if isinstance(value, dict):
        return {k: clean(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [clean(v) for v in value]
    if isinstance(value, (np.floating, float)):
        return float(value) if np.isfinite(value) else None
    if isinstance(value, (np.integer, np.bool_)):
        return value.item()
    return value


def sentence(text):
    """Trim a report line and start it with a capital letter."""
    text = text.strip()
    return text[:1].upper() + text[1:]


# ----------------------------------------------------------------------------- jugular vein
def jugular(image_b64, depth_cm):
    """One cross-section neck frame, skin at the top -> outline, vein measurements and a quality check."""
    image = read_image(image_b64)
    sp = spacing_mm(image, depth_cm)
    jugular_pipeline.FITS = JUGULAR_FITS
    with _lock:
        result = jugular_pipeline.predict_frame(image, sp)
    m, q = result["measurements"], result["quality"]
    return clean(dict(
        provenance=dict(siGenerated=True, method="U-Net segmentation ensemble with derived geometry", sourceDataset="SegThy", scope="Predicted overlay and derived measurements; excludes input scan"),
        measurements=dict(
            veinFound=m["vein_found"], areaMm2=m["area_mm2"], longAxisMm=m["long_axis_mm"], shortAxisMm=m["short_axis_mm"],
            flattening=m["flattening"], veinToArtery=m["vein_to_artery"], arteryAreaMm2=m["artery_area_mm2"]),
        quality=dict(accept=q["accept"], reasons=q["reasons"]),
        summary=sentence(report_line("", m, q)),
        overlayPng=overlay_png(result["mask"], image.shape, JUGULAR_COLOURS),
        legend=[dict(label="Jugular vein", colour="#4084f0"), dict(label="Carotid artery", colour="#e24848"), dict(label="Thyroid", colour="#f0c43c")],
        mmPerPixel=sp,
        models=len(jugular_pipeline.ensemble()),
    ))


# ----------------------------------------------------------------------------- heart
def heart_model():
    global _heart
    if _heart is None:
        net = camus_pipeline.UNet(4)
        net.load_state_dict(torch.load(HEART_MODEL / "unet.pt", map_location="cpu", weights_only=True)["state_dict"])
        reg = json.loads((HEART_MODEL / "ef_regressor.json").read_text())
        assert reg["features"] == list(FEATURES), "the saved regressor and the measurement code disagree on the features"
        reg = {k: np.asarray(v, dtype=float) if isinstance(v, list) and k != "features" else v for k, v in reg.items()}
        _heart = net.eval(), reg
    return _heart


def regress_ef(reg, features):
    """The frozen pipeline as plain arithmetic: median imputation, standard scaling, RBF support-vector regression."""
    x = np.array([np.nan if features[f] is None else features[f] for f in FEATURES], dtype=float)
    x = np.where(np.isfinite(x), x, reg["impute"])
    z = (x - reg["mean"]) / reg["scale"]
    return float(np.exp(-reg["gamma"] * ((reg["support_vectors"] - z) ** 2).sum(1)) @ reg["dual_coef"] + reg["intercept"])


def heart_masks(arrays):
    """arrays: {frame: 2D array as the training pipeline held it}. Returns {frame: label mask at that shape}."""
    net, _ = heart_model()
    batch = []
    for name in HEART_FRAMES:
        a = arrays[name].astype("float32")
        lo, hi = np.percentile(a, [1, 99])
        a = np.clip((a - lo) / max(float(hi - lo), 1e-6), 0, 1)
        batch.append(np.asarray(Image.fromarray(a).resize((SIZE, SIZE), Image.Resampling.BILINEAR)))
    with _lock, torch.no_grad():
        logits = net(torch.from_numpy(np.stack(batch))[:, None])
        return {name: F.interpolate(logits[j:j + 1], size=arrays[name].shape, mode="bilinear", align_corners=False).argmax(1)[0].numpy()
                for j, name in enumerate(HEART_FRAMES)}


def heart_measure(masks, spacings):
    """Label masks and (mm, mm) spacings per frame -> measurements, the ejection fraction and a status."""
    _, reg = heart_model()
    key = lambda name: tuple(name.split("_"))
    features, quality = patient_features({key(n): masks[n] for n in HEART_FRAMES}, {key(n): spacings[n] for n in HEART_FRAMES})
    ok = quality["status"] == "ok"
    return features, quality, (regress_ef(reg, features) if ok else None)


def heart(frames_b64, depth_cm):
    """Four frames (two- and four-chamber views, each at the fullest and emptiest point) -> ejection fraction."""
    if not isinstance(frames_b64, dict) or set(frames_b64) != set(HEART_FRAMES):
        raise BadInput("Send exactly four frames: " + ", ".join(HEART_FRAMES) + ".")
    images = {name: read_image(frames_b64[name]) for name in HEART_FRAMES}
    # The CAMUS frames were held sideways (first axis across the picture), so uploads are turned the same way.
    arrays = {name: np.ascontiguousarray(img.T) for name, img in images.items()}
    spacings = {name: (spacing_mm(images[name], depth_cm),) * 2 for name in HEART_FRAMES}
    masks = heart_masks(arrays)
    features, quality, ef = heart_measure(masks, spacings)
    reasons = []
    if ef is None:
        reasons.append("the left ventricle could not be measured in every frame")
    elif not 10 <= ef <= 85:
        reasons.append("the estimate is outside the range a heart normally shows")
    reasons += [f"{flag.split(':')[0].replace('_', ' ')}: {flag.split(':')[1].replace('_', ' ')}" for flag in quality["flags"]]
    return clean(dict(
        ejectionFraction=ef,
        provenance=dict(siGenerated=True, method="U-Net segmentation, derived geometry, and EF regression", sourceDataset="CAMUS", scope="Predicted overlays and derived measurements; excludes input scans"),
        geometryEjectionFraction=features["geom_ef"],
        endDiastolicVolumeMl=features["edv_ml"],
        endSystolicVolumeMl=features["esv_ml"],
        quality=dict(accept=ef is not None and not reasons, reasons=reasons),
        overlays={name: overlay_png(masks[name].T, images[name].shape, HEART_COLOURS) for name in HEART_FRAMES},
        legend=[dict(label="Left ventricle", colour="#e24848"), dict(label="Heart muscle", colour="#f0c43c"), dict(label="Left atrium", colour="#4084f0")],
    ))


def warm_up():
    """Load every model once, so a missing file is reported at start-up and the first scan is not slow."""
    jugular_pipeline.FITS = JUGULAR_FITS
    return dict(jugular_models=len(jugular_pipeline.ensemble()), heart_model=heart_model() is not None)
